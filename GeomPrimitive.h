/*
 * 文件名：GeomPrimitive.h
 * 职责：算法几何原语（值语义），输入/结果共用的统一几何词汇表
 *
 * 设计定位（2026-09 定稿，对照 Qt 隐式共享 + HALCON Region/XLD 模型）：
 *   - 本文件定义「线/点/轮廓」类的几何本体，是【输入基准几何】与【结果几何】
 *     共用的一套词汇表，不建两套类型；
 *   - 采用【值语义】：靠 Qt 隐式共享（copy-on-write）自动优化，
 *     读时零拷贝、写时自动 detach 隔离；禁止引入共享指针/引用（别名风险）；
 *   - 与 DrawShapeItem 的「面/区域」语义（ROI 框、屏蔽区、环形扇区）
 *     严格分家：这里是「线/点/轮廓」，那里是「面」。
 *
 * 语义对照：
 *   GeomPrimitive  → 几何本体（点/直线/线段/圆弧/圆/椭圆/轮廓），值语义，
 *                    既可作为工具输入基准，也可作为工具产出的几何结果；
 *   ResultGeom     → 只读结果封装：Geometry + 置信/标签/来源，无 mutable 接口，
 *                    保证结果几何不被误当输入改动（数据安全）；
 *   ToolInput      → 输入侧打包：图引用 + 面 ROI + 点线基准 + 参数（见使用时落地）。
 *
 * 单位约定（与 Pose2D / DrawShapeItem 保持一致）：
 *   - angle（直线方向角 / 椭圆旋转角）使用【弧度 radians】；
 *   - 圆弧 startAngle/span 使用【度 degrees】；
 *   - 坐标均为【图像像素坐标】（double，亚像素精度）。
 */
#pragma once

#include <QString>
#include <QPolygonF>

/*  结果几何类型：只表达「线/点/轮廓」类几何，与面/区域语义分离 */
enum GeomPrimitiveType
{
	Geom_Point = 0,     /*  单独一个点（圆心、交点、特征点） */
	Geom_Line,          /*  直线（无限长：基点 + 方向角） */
	Geom_Segment,       /*  线段（起终点） */
	Geom_Arc,           /*  圆弧（圆心/半径/起始角/跨度） */
	Geom_Circle,        /*  圆轮廓（圆心/半径，测量圆） */
	Geom_Ellipse,       /*  椭圆轮廓（中心/半轴 a,b/旋转角） */
	Geom_Contour        /*  开放或闭合轮廓（多点折线：边缘/卡尺散点） */
};

/* ========================================================================
 *  几何本体（值语义）：输入/结果共用的统一几何词汇
 *
 *  统一字段（按 type 决定有效性，风格与 DrawShapeItem 一致，但语义为线/点）：
 *    cx,cy        点 / 圆心 / 直线基点 / 线段起点 / 椭圆中心
 *    ex,ey        线段终点
 *    r            半径（圆/弧）、椭圆半长轴 a
 *    r2           椭圆半短轴 b（其余类型不用）
 *    angle        直线方向角（弧度）、椭圆旋转角（弧度）
 *    startAngle   圆弧起始角（度）
 *    span         圆弧跨度（度，正逆时针/负顺时针）
 *    contour      Geom_Contour 的折线点集（开放或闭合）
 * ======================================================================== */
struct GeomPrimitive
{
	GeomPrimitiveType type = Geom_Point;

	double cx = 0, cy = 0;           /*  点/圆心/直线基点/线段起点/椭圆中心 */
	double ex = 0, ey = 0;           /*  线段终点 */
	double r  = 0, r2 = 0;           /*  半径 / 椭圆半轴 a,b */
	double angle = 0;                /*  直线方向角 / 椭圆旋转角（弧度） */
	double startAngle = 0, span = 0; /*  圆弧（度） */
	QPolygonF contour;               /*  Geom_Contour 折线点集 */
};

/* ========================================================================
 *  只读结果封装：几何本体 + 结果元信息
 *
 *  【语义契约】本结构代表「算法产出」的几何，属只读输出：
 *    - 不提供任何 mutable 修改接口（字段虽为公开，但语义约定只读，
 *      调用方（可视化/判定/导出/下一步输入）只消费、不修改）；
 *    - 与 GeomPrimitive（可作可变输入基准）区分，保证结果几何的
 *      数据安全与来源可溯源（toolId 标记产生者）。
 * ======================================================================== */
struct ResultGeom
{
	GeomPrimitive geom;              /*  几何本体（值） */
	int     classId = -1;            /*  类别 id */
	QString label;                   /*  类别名 / 语义标签 */
	double  score = 0.0;             /*  拟合质量 / 置信度 (0~1) */
	QString toolId;                  /*  产生该结果的工具实例 id */
};
